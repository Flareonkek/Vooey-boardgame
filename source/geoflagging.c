void geo_init(void)
{
	char* my_loc  = setlocale(LC_ALL, ""); // Empty string as 2nd arg means "Give me the current locale" rather than "set"ing it.
	
	//my_loc = "fr_CA"; // Write what you want here to test other countries out
	//my_loc = "en_ZM";
	//my_loc = "English_United States.1252";
	//my_loc = "China WON";
	
	int loc_len = 0;
	for(; loc_len < 50; loc_len++)
	{
		if (my_loc[loc_len] == '\0')
			break;
	}
	
	printf("geo_init STEP 0: my_loc set to %s, loc_len to %i\n", my_loc, loc_len);
	
	printf("geo_init STEP 1: Look for identifiables in my_loc...\n");
	
	
	unsigned char found_match = 0;
	
	// For each string in identifiables...
	for (int i = 0; i < 247; i++)
	{
		// (Knowing the string's length)
		int identifiable_len = 0;
		for (int j=0; j<36; j++) {
			if (identifiables[i][j] == '\0') {
				identifiable_len = j;
				break;
			}
		}
		// (Only for identifiables that would fit in my_loc)
		if (identifiable_len > loc_len)
			continue;
		
		// We will check every possible way of imposing the identifiable on my_loc
		int n_checks = loc_len - identifiable_len + 1;
		
		//printf("checking \"%s\" against my_loc (%i checks)...\n", identifiables[i], n_checks);
		
		for (int j = 0; j < n_checks; j++)
		{
			// Check with identifiable starting on index j of my_loc
			unsigned char discrepency = 0;
			for (int k = 0; k < identifiable_len; k++)
			{
				if (identifiables[i][k] != my_loc[j+k]) {
					//printf("discrepency at k: %c != %c\n", identifiables[i][k], my_loc[j+k]);
					discrepency = 1;
					break;
				}
			}
			if (!discrepency)
			{
				// If you get here, the identifiable represents the correct flag
				printf("geo_init STEP 2: setting geoflag to %i\n", identifiables_flags[i]);
				geoflag = identifiables_flags[i];
				found_match = 1;
				break;
			}
		}
		if (found_match)
			break;
	}
	
	// If we couldn't find a match in identifiables, time to check countrycodes
	if (!found_match && loc_len >= 2)
	{
		// For each string in country_codes...
		for (int i = 0; i < 232; i++)
		{
			// We will check every possible way of imposing the countrycode on my_loc
			int n_checks = loc_len - 2 + 1;
			
			//printf("checking \"%s\" against my_loc (%i checks)...\n", countrycodes[i], n_checks);
			
			for (int j = 0; j < n_checks; j++)
			{
				// Check with identifiable starting on index j of my_loc
				unsigned char discrepency = 0;
				for (int k = 0; k < 2; k++)
				{
					if (countrycodes[i][k] != my_loc[j+k]) {
						//printf("discrepency at k: %c != %c\n", identifiables[i][k], my_loc[j+k]);
						discrepency = 1;
						break;
					}
				}
				if (!discrepency)
				{
					// If you get here, the identifiable represents the correct flag
					printf("geo_init STEP 2: setting geoflag to %i\n", identifiables_flags[i]);
					geoflag = countrycodes_flags[i];
					found_match = 1;
					break;
				}
			}
			if (found_match)
				break;
		}
	}
	
	// If we still couldn't find a match, we'll just use FLAG_UNKNOWN
	if (!found_match)
	{
		printf("geo_init STEP 2: failed to find matching identifiable or countrycode, setting geoflag to %i\n", FLAG_UNKNOWN);
		geoflag = FLAG_UNKNOWN;
	}
	
	// Finally, set the unsigned char pair to represent our geoflag
	geoflag_c0 = geoflag >> 8;
	geoflag_c1 = geoflag & 255;
	printf("geo_init STEP 3: setting geoflag_c0 to %i and geoflag_c1 to %i\n", geoflag_c0, geoflag_c1);
}
