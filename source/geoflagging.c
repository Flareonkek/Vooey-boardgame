// Set a source rectangle that can be used on geoflags.png to display a certain flag
void set_geoflag_source(int flag_index, int* sx, int* sy, int* sw, int* sh) {
	int col = flag_index % 17;
	int row = (flag_index - col) / 17;
	(*sx) = col*16;
	(*sy) = row*11;
	(*sw) = 16;
	(*sh) = 11;
}

int ucharpair_to_geoflag(unsigned char c0, unsigned char c1)
{
	int result = ((int)c0)<<8 | (int)c1;
	//printf("ucharpair_to_geoflag turned %i and %i into %i\n", c0, c1, result);
	return result;
}

