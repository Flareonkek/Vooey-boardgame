/*
I live in the United states, and my linux computer gives "en_US.UTF-8" for its locale
But my friend's windows computer gives "English_United States.1252"

Because of incoherent, self-contradictory documentation, it seems impossible to predict what strings windows would
give for other countries. I'd also like to imagine my code would work on any systems, with as few assumptions as
possible, so I'd like it to follow a fairly robust procedure for trying to interpret a locale string.

The idea here is to check for a long name of country, i.e. "United States", and if we can't find any like that, to then
check for a country code, i.e. "US". The reason is that, if we looked in the other order you might accidently find a
"country code" within the name of another country or something. Different capitalizations, and substitutions of both
dashes and underscores for spaces should also be tried before moving to country codes.
*/

